#!/usr/bin/env python3
"""gen_version_rc.py <wine-version> <wine-source-dir> <out-dir>

Write version resources for ddraw.dll, d3d8.dll, d3d9.dll and wined3d.dll
matching the reference qemu-3dfx DLLs, which carry Wine's own per-DLL
version.rc values (identical across Wine 1.8.7 .. 8.0.2):

  ddraw.dll    4.09.00.0904  "Wine DirectDraw"   (Wine's choice; games check it -
                                                   3DMark 99 refuses to start
                                                   without a ddraw version >= 4.06)
  d3d8/d3d9    5.3.1.904     "Wine Direct3D"
  wined3d.dll  <wine-version> "Wine D3D"

The copyright line is taken from the Wine tree's include/wine/wine_common_ver.rc,
as in the reference. Output: ddraw.rc, d3d8.rc, d3d9.rc, wined3d.rc.
"""
import os, re, sys

version, wine_src, out = sys.argv[1], sys.argv[2], sys.argv[3]

copyright_ = 'Copyright (c) 1993 the Wine project authors (see the file AUTHORS for a complete list)'
common = os.path.join(wine_src, 'include', 'wine', 'wine_common_ver.rc')
if os.path.exists(common):
    m = re.search(r'Copyright \(c\) 1993-[0-9]+[^"]*', open(common, errors='replace').read())
    if m:
        copyright_ = m.group(0)

nums = [int(x) for x in re.findall(r'\d+', version)][:3] + [0]
DLLS = {
    'ddraw':   ('Wine DirectDraw', '4.09.00.0904', (4, 9, 0, 904), 'Wine'),
    'd3d8':    ('Wine Direct3D',   '5.3.1.904',    (5, 3, 1, 904), 'Wine'),
    'd3d9':    ('Wine Direct3D',   '5.3.1.904',    (5, 3, 1, 904), 'Wine'),
    'wined3d': ('Wine D3D',        version,        tuple(nums[:4]), 'Wine D3D'),
}

TEMPLATE = '''/* Generated by docker/gen_version_rc.py - version resource matching the
 * reference qemu-3dfx {name}.dll (Wine {version}). */
#include <winver.h>

VS_VERSION_INFO VERSIONINFO
FILEVERSION {v[0]},{v[1]},{v[2]},{v[3]}
PRODUCTVERSION {v[0]},{v[1]},{v[2]},{v[3]}
FILEFLAGSMASK 0x3f
FILEFLAGS 0
FILEOS VOS_UNKNOWN
FILETYPE VFT_DLL
FILESUBTYPE VFT2_UNKNOWN
BEGIN
    BLOCK "StringFileInfo"
    BEGIN
        BLOCK "040904E4"
        BEGIN
            VALUE "CompanyName", "Microsoft Corporation"
            VALUE "FileDescription", "{desc}"
            VALUE "FileVersion", "{vstr}"
            VALUE "InternalName", "{name}"
            VALUE "LegalCopyright", "{copyright}"
            VALUE "OriginalFilename", "{name}.dll"
            VALUE "ProductName", "{product}"
            VALUE "ProductVersion", "{vstr}"
        END
    END
    BLOCK "VarFileInfo"
    BEGIN
        VALUE "Translation", 0x0409, 0x04E4
    END
END
'''

os.makedirs(out, exist_ok=True)
for name, (desc, vstr, v, product) in DLLS.items():
    with open(os.path.join(out, name + '.rc'), 'w') as f:
        f.write(TEMPLATE.format(name=name, version=version, desc=desc, vstr=vstr, v=v,
                                copyright=copyright_, product=product))
print('version resources for Wine %s -> %s (%s)' % (version, out, copyright_))
